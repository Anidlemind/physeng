#pragma once

#include <array>
#include <cctype>
#include <cstdint>
#include <string_view>

namespace renderer::detail {

// Five columns by seven rows; each row uses its five low bits.
inline std::array<std::uint8_t, 7> Glyph(char character) {
  constexpr std::string_view characters = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ.:/-";
  constexpr std::array<std::array<std::uint8_t, 7>, 40> glyphs{{
      {14, 17, 19, 21, 25, 17, 14}, {4, 12, 4, 4, 4, 4, 14},      {14, 17, 1, 2, 4, 8, 31},
      {30, 1, 1, 14, 1, 1, 30},     {2, 6, 10, 18, 31, 2, 2},     {31, 16, 16, 30, 1, 1, 30},
      {14, 16, 16, 30, 17, 17, 14}, {31, 1, 2, 4, 8, 8, 8},       {14, 17, 17, 14, 17, 17, 14},
      {14, 17, 17, 15, 1, 1, 14},   {14, 17, 17, 31, 17, 17, 17}, {30, 17, 17, 30, 17, 17, 30},
      {14, 17, 16, 16, 16, 17, 14}, {30, 17, 17, 17, 17, 17, 30}, {31, 16, 16, 30, 16, 16, 31},
      {31, 16, 16, 30, 16, 16, 16}, {14, 17, 16, 23, 17, 17, 15}, {17, 17, 17, 31, 17, 17, 17},
      {14, 4, 4, 4, 4, 4, 14},      {7, 2, 2, 2, 2, 18, 12},      {17, 18, 20, 24, 20, 18, 17},
      {16, 16, 16, 16, 16, 16, 31}, {17, 27, 21, 21, 17, 17, 17}, {17, 25, 21, 19, 17, 17, 17},
      {14, 17, 17, 17, 17, 17, 14}, {30, 17, 17, 30, 16, 16, 16}, {14, 17, 17, 17, 21, 18, 13},
      {30, 17, 17, 30, 20, 18, 17}, {15, 16, 16, 14, 1, 1, 30},   {31, 4, 4, 4, 4, 4, 4},
      {17, 17, 17, 17, 17, 17, 14}, {17, 17, 17, 17, 17, 10, 4},  {17, 17, 17, 21, 21, 21, 10},
      {17, 17, 10, 4, 10, 17, 17},  {17, 17, 10, 4, 4, 4, 4},     {31, 1, 2, 4, 8, 16, 31},
      {0, 0, 0, 0, 0, 12, 12},      {0, 12, 12, 0, 12, 12, 0},    {1, 2, 2, 4, 8, 8, 16},
      {0, 0, 0, 31, 0, 0, 0},
  }};
  const auto index =
      characters.find(static_cast<char>(std::toupper(static_cast<unsigned char>(character))));
  return index == characters.npos ? std::array<std::uint8_t, 7>{} : glyphs[index];
}

} // namespace renderer::detail
